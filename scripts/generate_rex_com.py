"""Generate `rex_com/src/*.rs` from CommonLib `REX/W32/*.h` COM interfaces.

For every `struct __declspec(novtable, uuid(...)) IFoo : public IBar { virtual ... = 0; }`
this emits:

- `#[repr(C)] pub struct IFoo { pub vtbl: *const IFooVtbl }`
- `#[repr(C)] pub struct IFooVtbl { pub base: IBarVtbl, pub Method: *const c_void, ... }`
- `impl IFoo { pub const IID: GUID = ...; }`

Slots are raw pointers named after the C++ method so the order can never
drift from the header; callers transmute a slot to its typed signature (see
the hand-written wrappers in `rex/com/mod.rs`).

Usage: python scripts/generate_rex_com.py [COMMONLIB_DIR]
"""
import os
import re
import sys

COMMONLIB = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('COMMONLIB_DIR', r'D:/Programming/cpp/CommonLibSSE-NG')
W32 = os.path.join(COMMONLIB, 'include', 'REX', 'W32')
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'rex_com', 'src')

HEADERS = {
    'unknown': ['COM.h'],
    'dxgi': ['DXGI.h'],
    'd3d11': ['D3D11.h'],
}

DECL = re.compile(
    r'struct\s+__declspec\(\s*novtable\s*,\s*uuid\(\s*"([0-9A-Fa-f-]+)"\s*\)\s*\)\s*'
    r'(\w+)\s*(?::\s*public\s+(\w+))?\s*\{(\};|.*?\n\t\};)',
    re.S)
# Older headers spell IUnknown without __declspec on the same line; handle it explicitly.
UNKNOWN = re.compile(r'struct\s+__declspec\(\s*novtable\s*,\s*uuid\(\s*"([0-9A-Fa-f-]+)"\s*\)\s*\)\s*IUnknown\s*\{(.*?)\n\t\};', re.S)
METHOD = re.compile(r'virtual\s+[^;{]*?\b(\w+)\s*\([^;]*?\)\s*(?:const\s*)?=\s*0\s*;', re.S)


def guid_literal(uuid):
    p = uuid.split('-')
    d4 = p[3] + p[4]
    bytes_ = ', '.join(f'0x{d4[i:i + 2]}' for i in range(0, 16, 2))
    return f'GUID {{ data1: 0x{p[0]}, data2: 0x{p[1]}, data3: 0x{p[2]}, data4: [{bytes_}] }}'


def parse(path):
    text = open(path, encoding='utf-8').read()
    out = []
    for m in DECL.finditer(text):
        uuid, name, base, body = m.groups()
        methods = []
        seen = set()
        for mm in METHOD.finditer(body):
            n = mm.group(1)
            # Overloads cannot happen in COM vtables, but guard against
            # convenience templates that sneak in.
            if n in seen:
                n = f'{n}_{len(seen)}'
            seen.add(n)
            methods.append(n)
        out.append((name, base, uuid, methods))
    return out


def emit(module, interfaces, known):
    lines = [
        '// AUTO-GENERATED by scripts/generate_rex_com.py from CommonLib `REX/W32` headers. Do not edit.',
        '#![allow(non_snake_case, non_camel_case_types, clippy::all)]',
        '',
        'use core::ffi::c_void;',
        '',
        'use super::GUID;',
    ]
    bases = sorted({b for _, b, _, _ in interfaces if b and b not in {i[0] for i in interfaces}})
    if bases:
        lines.append(f"use super::{{{', '.join(f'{b}Vtbl' for b in bases)}}};")
    lines.append('')
    for name, base, uuid, methods in interfaces:
        lines.append(f'/// C++ `REX::W32::{name}`')
        lines.append('#[repr(C)]')
        lines.append(f'pub struct {name} {{')
        lines.append(f'    pub vtbl: *const {name}Vtbl,')
        lines.append('}')
        lines.append('')
        lines.append(f'impl {name} {{')
        lines.append(f'    pub const IID: GUID = {guid_literal(uuid)};')
        lines.append('}')
        lines.append('')
        lines.append(f'/// Virtual table of [`{name}`].')
        lines.append('#[repr(C)]')
        lines.append(f'pub struct {name}Vtbl {{')
        if base:
            lines.append(f'    pub base: {base}Vtbl,')
        for meth in methods:
            lines.append(f'    pub {meth}: *const c_void,')
        lines.append('}')
        lines.append('')
        known.add(name)
    return '\n'.join(lines) + '\n'


def main():
    os.makedirs(OUT, exist_ok=True)
    known = set()
    for module, headers in HEADERS.items():
        interfaces = []
        for h in headers:
            interfaces.extend(parse(os.path.join(W32, h)))
        if module == 'unknown':
            interfaces = [i for i in interfaces if i[0] == 'IUnknown']
        if not interfaces:
            raise SystemExit(f'no interfaces parsed for {module}')
        open(os.path.join(OUT, f'{module}.rs'), 'w', encoding='utf-8', newline='\n').write(emit(module, interfaces, known))
        print(f'{module}: {len(interfaces)} interfaces')


if __name__ == '__main__':
    main()
